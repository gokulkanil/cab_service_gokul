// Builds supabase/seed.sql from supabase/seed/content.json.
// content.json is the single source for the starting content; the app also
// reads it directly when no database is connected yet.
//
// Usage: npm run db:seed-sql (from the repository root)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dbDir = join(dirname(fileURLToPath(import.meta.url)), '..'); // the supabase/ folder
const content = JSON.parse(readFileSync(join(dbDir, 'seed/content.json'), 'utf8'));

/** SQL literal for a JS value. */
function lit(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`Bad number: ${value}`);
    return String(value);
  }
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (Array.isArray(value)) return `array[${value.map(lit).join(', ')}]::text[]`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

const row = (values) => `(${values.map(lit).join(', ')})`;
const rows = (list, fn) => list.map((item) => '  ' + row(fn(item))).join(',\n');

const s = content.siteSettings;
const out = [];

out.push(`-- Generated by scripts/generate-seed-sql.mjs from supabase/seed/content.json.
-- Do not edit by hand: change content.json and run \`npm run db:seed-sql\`.
-- Safe to run more than once: existing rows are left as they are.

begin;
`);

out.push(`insert into public.site_settings
  (id, business_name, tagline, site_url, phone_e164, phone_display, whatsapp_e164, whatsapp_message,
   email, region_label, service_area, address_locality, address_region, address_country)
values
  ${row([1, s.businessName, s.tagline, s.siteUrl, s.phoneE164, s.phoneDisplay, s.whatsappE164, s.whatsappMessage,
    s.email, s.regionLabel, s.serviceArea, s.addressLocality, s.addressRegion, s.addressCountry])}
on conflict (id) do nothing;
`);

out.push(`insert into public.vehicle_categories (slug, name, seats, luggage_bags, has_ac, sort_order)
values
${rows(content.vehicleCategories, (c) => [c.slug, c.name, c.seats, c.luggageBags, c.hasAc, c.sortOrder])}
on conflict (slug) do nothing;
`);

out.push(`insert into public.vehicles
  (category_id, slug, make, model, tagline, description, best_for, image_path, is_featured, status, sort_order)
select c.id, v.slug, v.make, v.model, v.tagline, v.description, v.best_for, v.image_path, v.is_featured,
       v.status::public.vehicle_status, v.sort_order
from (values
${rows(content.vehicles, (v) => [v.category, v.slug, v.make, v.model, v.tagline, v.description, v.bestFor,
  v.imagePath ?? null, v.isFeatured ?? false, v.status ?? 'active', v.sortOrder])}
) as v(category, slug, make, model, tagline, description, best_for, image_path, is_featured, status, sort_order)
join public.vehicle_categories c on c.slug = v.category
on conflict (slug) do nothing;
`);

out.push(`insert into public.place_categories (slug, name, sort_order)
values
${rows(content.placeCategories, (c) => [c.slug, c.name, c.sortOrder])}
on conflict (slug) do nothing;
`);

out.push(`insert into public.places
  (slug, kind, name, short_name, code, region, description, tag_label, color_from, color_to, image_path,
   is_transfer_hub, sort_order)
select p.slug, p.kind::public.place_kind, p.name, p.short_name, p.code, p.region, p.description, p.tag_label,
       p.color_from, p.color_to, p.image_path, p.is_transfer_hub, p.sort_order
from (values
${rows(content.places, (p) => [p.slug, p.kind, p.name, p.shortName ?? null, p.code ?? null, p.region ?? null,
  p.description ?? '', p.tagLabel ?? null, p.colorFrom ?? null, p.colorTo ?? null, p.imagePath ?? null,
  p.isTransferHub ?? false, p.sortOrder])}
) as p(slug, kind, name, short_name, code, region, description, tag_label, color_from, color_to, image_path,
       is_transfer_hub, sort_order)
on conflict (slug) do nothing;
`);

const links = content.places.flatMap((p) => (p.categories ?? []).map((c) => [p.slug, c]));
if (links.length) {
  out.push(`insert into public.place_category_links (place_id, category_id)
select p.id, c.id
from (values
${links.map((l) => '  ' + row(l)).join(',\n')}
) as l(place_slug, category_slug)
join public.places p on p.slug = l.place_slug
join public.place_categories c on c.slug = l.category_slug
on conflict do nothing;
`);
}

out.push(`insert into public.services (slug, title, summary, icon, hero_label, is_featured, sort_order)
values
${rows(content.services, (v) => [v.slug, v.title, v.summary, v.icon, v.heroLabel ?? null, v.isFeatured ?? false, v.sortOrder])}
on conflict (slug) do nothing;
`);

out.push(`insert into public.routes (from_place_id, to_place_id, board_label, via_note, duration_minutes, sort_order)
select f.id, t.id, r.board_label, r.via_note, r.duration_minutes, r.sort_order
from (values
${rows(content.routes, (r) => [r.from, r.to, r.boardLabel, r.viaNote, r.durationMinutes, r.sortOrder])}
) as r(from_slug, to_slug, board_label, via_note, duration_minutes, sort_order)
join public.places f on f.slug = r.from_slug
join public.places t on t.slug = r.to_slug
on conflict (from_place_id, to_place_id) do nothing;
`);

// These tables have no natural key, so they are only seeded when empty.
for (const [table, cols, list, fn] of [
  ['travel_tips', 'title, body, sort_order', content.travelTips, (t) => [t.title, t.body, t.sortOrder]],
  ['faqs', 'question, answer, sort_order', content.faqs, (f) => [f.question, f.answer, f.sortOrder]],
  ['features', 'title, body, icon, sort_order', content.features, (f) => [f.title, f.body, f.icon, f.sortOrder]],
]) {
  out.push(`insert into public.${table} (${cols})
select * from (values
${rows(list, fn)}
) as v(${cols})
where not exists (select 1 from public.${table});
`);
}

out.push('commit;\n');

const target = join(dbDir, 'seed.sql');
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target}`);
